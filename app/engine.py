"""Deterministic Nginx config renderer, with no arbitrary directive input."""
from .validation import HostInput, StreamInput, nginx_target, cert_matches_domain, clean_domain, clean_target

FALLBACK_FILE = '__proxycircuit_error_page.html'
FALLBACK_LOCATION = r'''
    location = /__proxycircuit_error_page.html {
        internal;
        root /var/www/rpmgr-fallback;
        default_type text/html;
        add_header Cache-Control "no-store" always;
        add_header X-Robots-Tag "noindex, nofollow, noarchive" always;
        add_header X-Content-Type-Options "nosniff" always;
        add_header Content-Security-Policy "default-src 'none'; style-src 'unsafe-inline'; img-src data: https:; font-src data:; script-src 'none'; connect-src 'none'; form-action 'none'; base-uri 'none'; frame-ancestors 'none'" always;
    }
'''

HTTP_HEADER = r'''# Generated by ProxyCircuit. Do not edit manually.
# This file is included from Nginx http context.
map $http_upgrade $rpmgr_upgrade_connection {
    default upgrade;
    '' close;
}

server {
    listen 80 default_server;
    server_name _;
    location ^~ /.well-known/acme-challenge/ {
        root /var/www/rpmgr-acme;
        default_type text/plain;
        try_files $uri =404;
    }
    error_page 404 /__proxycircuit_error_page.html;
    location / { return 404; }
''' + FALLBACK_LOCATION + r'''
}

# Unknown HTTPS requests can display HTML only after a TLS handshake.
# The local admin certificate is not generally trusted for arbitrary domains.
server {
    listen 443 ssl default_server;
    http2 on;
    server_name _;
    ssl_certificate /etc/rpmgr/admin.crt;
    ssl_certificate_key /etc/rpmgr/admin.key;
    ssl_protocols TLSv1.2 TLSv1.3;
    error_page 404 /__proxycircuit_error_page.html;
    location / { return 404; }
''' + FALLBACK_LOCATION + r'''
}

server {
    listen 127.0.0.1:18081;
    server_name localhost;
    location = /nginx_status {
        stub_status;
        allow 127.0.0.1;
        deny all;
    }
}
'''

def proxy_location(row):
    target = nginx_target(row['upstream_host'])
    scheme = row['upstream_scheme']
    output = [
        '    location / {',
        f'        proxy_pass {scheme}://{target}:{int(row["upstream_port"])};',
        '        proxy_http_version 1.1;',
        '        proxy_intercept_errors on;',
        '        proxy_set_header Host ' + (clean_target(row['upstream_host_header']) if row.get('upstream_host_header') else '$host') + ';',
        '        proxy_set_header X-Real-IP $remote_addr;',
        '        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
        '        proxy_set_header X-Forwarded-Proto $scheme;',
        '        proxy_connect_timeout 10s;',
        '        proxy_read_timeout 300s;',
    ]
    if row['websocket']:
        output.extend(('        proxy_set_header Upgrade $http_upgrade;',
                       '        proxy_set_header Connection $rpmgr_upgrade_connection;'))
    else:
        output.append('        proxy_set_header Connection "";')
    if scheme == 'https':
        output.extend(('        proxy_ssl_server_name on;',
                       '        proxy_ssl_verify on;',
                       '        proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;',
                       '        proxy_ssl_verify_depth 4;'))
        # TLS server name may differ from the network IP (e.g. self-signed admin cert).
        # Keep verification enabled; never use proxy_ssl_verify off as a workaround.
        if row.get('upstream_tls_name'):
            output.append(f"        proxy_ssl_name {clean_domain(row['upstream_tls_name'])};")
    output.append('    }')
    return '\n'.join(output)

def render_http(hosts, certificates):
    certs = {c['id']: c for c in certificates}
    lines = [HTTP_HEADER]
    for raw in sorted(hosts, key=lambda r: r['domain']):
        row = dict(raw)
        validated = HostInput(**row)
        if not validated.enabled:
            continue
        domain = validated.domain
        cert = None
        if validated.certificate_id:
            cert = certs.get(validated.certificate_id)
            if not cert or cert['status'] != 'ready' or not cert.get('fullchain_path') or not cert.get('privkey_path'):
                raise ValueError(f'{domain}: Zugewiesenes SSL-Zertifikat ist nicht bereit')
            if not cert_matches_domain(cert['domain'], domain):
                raise ValueError(f'{domain}: Zertifikat deckt die Domain nicht ab')
        lines += [f'\n# HTTP host: {domain}', 'server {', '    listen 80;',
                  f'    server_name {domain};',
                  '    error_page 502 503 504 /__proxycircuit_error_page.html;',
                  FALLBACK_LOCATION,
                  '    location ^~ /.well-known/acme-challenge/ {',
                  '        root /var/www/rpmgr-acme;',
                  '        default_type text/plain;',
                  '        try_files $uri =404;', '    }']
        if validated.force_https:
            lines += ['    location / { return 301 https://$host$request_uri; }']
        else:
            lines.append(proxy_location(row))
        lines.append('}')
        if cert:
            lines += [f'\n# HTTPS host: {domain}', 'server {',
                      '    listen 443 ssl;', '    http2 on;', f'    server_name {domain};',
                      '    error_page 502 503 504 /__proxycircuit_error_page.html;',
                      FALLBACK_LOCATION,
                      f'    ssl_certificate {cert["fullchain_path"]};',
                      f'    ssl_certificate_key {cert["privkey_path"]};',
                      '    ssl_protocols TLSv1.2 TLSv1.3;',
                      '    ssl_session_timeout 1d;',
                      '    ssl_session_cache shared:RPMGR_SSL:10m;',
                      proxy_location(row), '}']
    return '\n'.join(lines) + '\n'

def render_stream(streams, enabled_http=True):
    lines = ['# Generated by ProxyCircuit. Included at Nginx main context.', 'stream {',
             '    access_log off;']
    used = set()
    for raw in sorted(streams, key=lambda r: (r['protocol'], r['listen_port'])):
        row = dict(raw)
        data = StreamInput(**row)
        if not data.enabled:
            continue
        key = (data.protocol, data.listen_port)
        if key in used:
            raise ValueError(f'Port {data.listen_port}/{data.protocol} ist mehrfach belegt')
        used.add(key)
        if data.protocol == 'tcp' and data.listen_port in (80, 443, 18081, 9443):
            raise ValueError(f'Port {data.listen_port}/TCP ist für HTTP, Monitoring oder Verwaltung reserviert')
        target = nginx_target(data.target_host)
        lines.extend([f'    # {data.label}', '    server {',
                      f'        listen {data.listen_port}' + (' udp;' if data.protocol == 'udp' else ';'),
                      f'        proxy_pass {target}:{data.target_port};',
                      '        proxy_connect_timeout 10s;',
                      f'        proxy_timeout {data.timeout_seconds}s;', '    }'])
    lines.append('}')
    return '\n'.join(lines) + '\n'
